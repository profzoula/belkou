import DOMPurify from "isomorphic-dompurify";

const BLOG_HTML_CONFIG = {
  ALLOWED_TAGS: [
    "p",
    "br",
    "strong",
    "b",
    "em",
    "i",
    "u",
    "ul",
    "ol",
    "li",
    "a",
    "h1",
    "h2",
    "h3",
    "h4",
    "img",
    "table",
    "thead",
    "tbody",
    "tr",
    "th",
    "td",
    "blockquote",
    "cite",
    "pre",
    "code",
    "details",
    "summary",
    "hr",
    "div",
    "section",
    "aside",
    "figure",
    "figcaption",
    "nav",
    "iframe",
    "video",
    "audio",
    "source",
  ],
  ALLOWED_ATTR: [
    "href",
    "src",
    "alt",
    "title",
    "target",
    "rel",
    "class",
    "style",
    "loading",
    "controls",
    "allowfullscreen",
    "allow",
    "download",
    "width",
    "height",
    "aria-hidden",
    "aria-label",
  ],
  ALLOW_DATA_ATTR: false,
};

export function sanitizeBlogHtml(html: string): string {
  return DOMPurify.sanitize(html, BLOG_HTML_CONFIG);
}
